import Foundation

enum AppLanguage: String, CaseIterable {
    case zh
    case en
    case ru

    var label: String {
        switch self {
        case .zh: return "中文"
        case .en: return "English"
        case .ru: return "Русский"
        }
    }
}

enum L10n {
    static var current: AppLanguage {
        if let raw = UserDefaults.standard.string(forKey: Prefs.language),
           let language = AppLanguage(rawValue: raw) {
            return language
        }
        return systemDefault
    }

    static var systemDefault: AppLanguage {
        let code = Locale.preferredLanguages.first?.prefix(2).lowercased() ?? "en"
        switch code {
        case "zh": return .zh
        case "ru": return .ru
        default: return .en
        }
    }

    static var outputLanguageName: String {
        switch current {
        case .zh: return "Simplified Chinese"
        case .en: return "English"
        case .ru: return "Russian"
        }
    }

    static var translationTargetName: String {
        switch current {
        case .zh: return "Simplified Chinese"
        case .en: return "English"
        case .ru: return "Russian"
        }
    }

    static var translationFallbackName: String {
        switch current {
        case .zh: return "English"
        case .en: return "Simplified Chinese"
        case .ru: return "English"
        }
    }

